"""Generate the app's copy of upstream's shared error sentences.

Reads public/utils/friendly-error.js (REFUSAL_MESSAGES, CASE_MESSAGES, CASE_PARAMS,
GONE_REASONS, PARAM_MAX) and writes a Kotlin object, so the mapping is usable from pure
unit tests and stays in step with the pinned upstream version.

    python3 -I extract_friendly_errors.py <upstream checkout> <output .kt>
"""
import re
import sys
from pathlib import Path


def block(src: str, name: str) -> str:
    m = re.search(r"export const " + name + r" = new (?:Map|Set)\(\[(.*?)\n\]\);", src, re.S)
    if not m:
        sys.exit(f"friendly-error.js: {name} not found")
    # Drop comments so quoted words inside them are not read as entries.
    return re.sub(r"//[^\n]*", "", m.group(1))


def pairs(body: str) -> list[tuple[str, str]]:
    return re.findall(r"\[\s*'([^']+)'\s*,\s*'([^']+)'\s*\]", body)


def kt(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main() -> None:
    upstream, out = Path(sys.argv[1]), Path(sys.argv[2])
    src = (upstream / "public/utils/friendly-error.js").read_text(encoding="utf-8")
    refusals = pairs(block(src, "REFUSAL_MESSAGES"))
    cases = pairs(block(src, "CASE_MESSAGES"))
    params = [
        (reason, re.findall(r"'([^']+)'", names))
        for reason, names in re.findall(r"\[\s*'([^']+)'\s*,\s*\[([^\]]*)\]\s*\]", block(src, "CASE_PARAMS"))
    ]
    gone = re.findall(r"'([^']+)'", block(src, "GONE_REASONS"))
    m = re.search(r"const PARAM_MAX = ([0-9_]+);", src)
    if not m:
        sys.exit("friendly-error.js: PARAM_MAX not found")
    param_max = m.group(1).replace("_", "")
    if not (refusals and cases and gone):
        sys.exit("friendly-error.js: an empty table, the format changed")

    def entries(rows):
        return "\n".join(f"        {kt(a)} to {kt(b)}," for a, b in rows)

    lines = [
        "// Generated by upstream/scripts/extract_friendly_errors.py from upstream's",
        "// public/utils/friendly-error.js. Do not edit; run upstream/sync.sh.",
        "package io.github.marcomow.yuvomi.core.api",
        "",
        "internal object FriendlyErrorTable {",
        "    /** `REFUSAL_MESSAGES`: the reason of a 403 -> its sentence key. */",
        "    val REFUSALS: Map<String, String> = mapOf(",
        entries(refusals),
        "    )",
        "",
        "    /** `CASE_MESSAGES`: a case the server names (`reason`) -> its sentence key. */",
        "    val CASES: Map<String, String> = mapOf(",
        entries(cases),
        "    )",
        "",
        "    /** `CASE_PARAMS`: the whole numbers a case's sentence needs from `params`. */",
        "    val PARAMS: Map<String, List<String>> = mapOf(",
        "\n".join(f"        {kt(r)} to listOf({', '.join(kt(n) for n in names)})," for r, names in params),
        "    )",
        "",
        "    /** `GONE_REASONS`: the target of the action no longer exists. */",
        "    val GONE: Set<String> = setOf(",
        "\n".join(f"        {kt(r)}," for r in gone),
        "    )",
        "",
        f"    const val PARAM_MAX: Long = {param_max}L",
        "}",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
